package main

// createConfig.go turns the live wizard state into an install config file. The
// builder is pure: tests do not need root, podman or a terminal. The writer is
// the only side effect and it is careful with credentials: mode 0600, a fresh
// temp file, and an atomic rename.

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

const installConfigHeader = "# Generated by k8s-installer-tui --create.\n" +
	"# This file contains plaintext SSH credentials; keep it mode 0600.\n\n"

// createConfigInput is every value the wizard has collected by the time the
// Save Config page is reached. Keeping it explicit makes the builder testable
// without touching package globals.
type createConfigInput struct {
	ProjectPath    string
	HostnamePrefix string
	Inventory      Inventory
	ExtraVars      map[string]any
	App            AppConfig
	HAMode         string
	VIP            string
	CheckConflicts bool
	MirrorEnabled  bool
	Mirrors        map[string]string
	SSHUser        string
	SSHPort        int
	SSHPassword    string
	SSHKeyFile     string
	SudoPassword   string
}

// networkVarKeys and haVarKeys are the variables that own a structured section
// in the file. They must not be copied into extra_vars, which is merged last by
// buildExtraVars and would silently override that section on the next run.
var networkVarKeys = map[string]struct{}{
	"kube_network_plugin":    {},
	"kube_service_addresses": {},
	"kube_pods_subnet":       {},
	"calico_vxlan_mode":      {},
}

var haVarKeys = map[string]struct{}{
	"loadbalancer_apiserver_localhost":   {},
	"kube_vip_enabled":                   {},
	"kube_vip_controlplane_enabled":      {},
	"kube_vip_arp_enabled":               {},
	"kube_proxy_strict_arp":              {},
	"kube_vip_lb_enable":                 {},
	"kube_vip_address":                   {},
	"loadbalancer_apiserver":             {},
	"apiserver_loadbalancer_domain_name": {},
}

func buildInstallConfig(in createConfigInput) (*installConfig, error) {
	if in.SSHPassword != "" && in.SSHKeyFile != "" {
		return nil, fmt.Errorf("ssh: use either ssh.password or ssh.key_file, not both")
	}

	hosts, err := hostsFromInventory(in.Inventory)
	if err != nil {
		return nil, err
	}

	features, extra, err := classifyVars(in.App, in.ExtraVars)
	if err != nil {
		return nil, err
	}

	check := in.CheckConflicts
	cfg := &installConfig{
		Version:        1,
		ProjectPath:    in.ProjectPath,
		HostnamePrefix: normalizedHostnamePrefix(in.HostnamePrefix),
		SSH: installSSH{
			User:         in.SSHUser,
			Port:         in.SSHPort,
			Password:     in.SSHPassword,
			KeyFile:      in.SSHKeyFile,
			SudoPassword: in.SudoPassword,
		},
		Hosts:     installHosts{Detailed: hosts},
		HA:        haFromState(in),
		Network:   networkFromState(in),
		Mirror:    installMirror{Enabled: in.MirrorEnabled},
		Features:  features,
		ExtraVars: extra,
	}
	cfg.Network.CheckConflicts = &check

	if in.MirrorEnabled {
		cfg.Mirror.URLs = mirrorURLs(in.App, in.Mirrors, in.ExtraVars)
	}

	// Run the same defaults and validation --config applies. A generated file
	// that would not load is a bug, not something to write and discover later.
	if err := cfg.applyDefaults(in.App); err != nil {
		return nil, err
	}
	if err := cfg.validate(in.App); err != nil {
		return nil, err
	}

	return cfg, nil
}

func hostsFromInventory(inv Inventory) ([]installHost, error) {
	names := make([]string, 0, len(inv.All.Hosts))
	for name := range inv.All.Hosts {
		names = append(names, name)
	}
	sort.Strings(names)

	hosts := make([]installHost, 0, len(names))
	for _, name := range names {
		host := inv.All.Hosts[name]
		if strings.TrimSpace(host.Ip) == "" {
			return nil, fmt.Errorf("hosts: %q has no IP address", name)
		}

		roles := rolesForHost(inv, name)
		if len(roles) == 0 {
			return nil, fmt.Errorf("hosts: %q has no role in the inventory", name)
		}

		hosts = append(hosts, installHost{
			Name:        name,
			IP:          host.Ip,
			AccessIP:    host.Access_ip,
			AnsibleHost: host.Ansible_host,
			Roles:       roles,
			Labels:      copyStringMap(host.Node_labels),
			Taints:      append([]string(nil), host.Node_taints...),
		})
	}

	return hosts, nil
}

// rolesForHost keeps a fixed order so the generated file is deterministic.
func rolesForHost(inv Inventory, name string) []string {
	var roles []string
	if _, ok := inv.All.Children.Kube_control_plane.Hosts[name]; ok {
		roles = append(roles, roleControlPlane)
	}
	if _, ok := inv.All.Children.Kube_node.Hosts[name]; ok {
		roles = append(roles, roleNode)
	}
	if _, ok := inv.All.Children.Etcd.Hosts[name]; ok {
		roles = append(roles, roleEtcd)
	}
	if _, ok := inv.All.Children.Calico_rr.Hosts[name]; ok {
		roles = append(roles, roleCalicoRR)
	}

	return roles
}

// classifyVars splits extraVars into the structured features section and the
// genuine extra_vars remainder. Every key owned by another section is removed:
// extra_vars wins over all of them when buildExtraVars runs.
func classifyVars(app AppConfig, extra map[string]any) (map[string]any, map[string]any, error) {
	defaults, err := configurableVarTypes(app)
	if err != nil {
		return nil, nil, fmt.Errorf("features: %w", err)
	}

	features := make(map[string]any, len(defaults))
	for key, value := range defaults {
		if value == nil {
			continue
		}
		features[key] = deepCopyValue(value)
	}
	for key, value := range extra {
		if _, ok := defaults[key]; ok && value != nil {
			features[key] = deepCopyValue(value)
		}
	}

	mirrorKeys := defaultMirrorKeys(app)
	extraOut := make(map[string]any)
	for key, value := range extra {
		if _, ok := defaults[key]; ok {
			continue
		}
		if _, ok := networkVarKeys[key]; ok {
			continue
		}
		if _, ok := haVarKeys[key]; ok {
			continue
		}
		if _, ok := mirrorKeys[key]; ok {
			continue
		}
		if defaultValue, ok := app.Default_vars[key]; ok && reflect.DeepEqual(defaultValue, value) {
			// buildExtraVars re-applies the current default; writing it again
			// would only pin an old copy of config.yaml.
			continue
		}
		extraOut[key] = deepCopyValue(value)
	}

	return features, extraOut, nil
}

func defaultMirrorKeys(app AppConfig) map[string]struct{} {
	keys := make(map[string]struct{})
	for _, item := range app.Default_mirrors {
		for key := range item {
			keys[key] = struct{}{}
		}
	}

	return keys
}

// mirrorURLs records every configured mirror key. The Mirror page's live values
// win, then extraVars (a loaded project), then the config.yaml default.
func mirrorURLs(app AppConfig, mirrors map[string]string, extra map[string]any) map[string]string {
	urls := make(map[string]string)
	for _, item := range app.Default_mirrors {
		for key, defaultValue := range item {
			if value, ok := mirrors[key]; ok {
				urls[key] = value
				continue
			}
			if value, ok := extra[key].(string); ok {
				urls[key] = value
				continue
			}
			urls[key] = defaultValue
		}
	}

	return urls
}

func haFromState(in createConfigInput) installHA {
	mode := strings.TrimSpace(in.HAMode)
	if mode == "" {
		if stringValue(in.ExtraVars, "kube_vip_address") != "" {
			mode = "kube-vip"
		} else {
			mode = "localhost loadbalancing"
		}
	}

	ha := installHA{Mode: mode}
	if normalizeHAMode(mode) == "kube-vip" {
		ha.VIP = strings.TrimSpace(in.VIP)
		if ha.VIP == "" {
			ha.VIP = stringValue(in.ExtraVars, "kube_vip_address")
		}
	}

	return ha
}

func networkFromState(in createConfigInput) installNetwork {
	plugin := stringValue(in.ExtraVars, "kube_network_plugin")
	if plugin == "" {
		plugin = stringValue(in.App.Default_vars, "kube_network_plugin")
	}
	if plugin == "" {
		plugin = "flannel"
	}

	network := installNetwork{
		Plugin:      strings.ToLower(plugin),
		ServiceCIDR: stringValue(in.ExtraVars, "kube_service_addresses"),
		PodCIDR:     stringValue(in.ExtraVars, "kube_pods_subnet"),
	}
	if network.Plugin == "calico" {
		network.CalicoVxlanMode = stringValue(in.ExtraVars, "calico_vxlan_mode")
		if network.CalicoVxlanMode == "" {
			network.CalicoVxlanMode = "Always"
		}
	}

	return network
}

func stringValue(values map[string]any, key string) string {
	value, _ := values[key].(string)

	return strings.TrimSpace(value)
}

func normalizedHostnamePrefix(prefix string) string {
	prefix = strings.TrimSpace(prefix)
	if hostnamePattern.MatchString(prefix) && len(prefix) <= 63 {
		return prefix
	}

	return "node"
}

func copyStringMap(values map[string]string) map[string]string {
	if values == nil {
		return nil
	}
	copied := make(map[string]string, len(values))
	for key, value := range values {
		copied[key] = value
	}

	return copied
}

func marshalInstallConfig(cfg *installConfig) ([]byte, error) {
	var buffer bytes.Buffer
	encoder := yaml.NewEncoder(&buffer)
	encoder.SetIndent(2)
	if err := encoder.Encode(cfg); err != nil {
		return nil, err
	}
	if err := encoder.Close(); err != nil {
		return nil, err
	}

	return buffer.Bytes(), nil
}

// writeInstallConfigFile writes the file atomically and with tight permissions.
// It refuses to create a missing directory: a mistyped output path should be an
// error, not a surprise tree on disk.
func writeInstallConfigFile(path string, cfg *installConfig) (string, error) {
	abs, err := expandHomePath(path)
	if err != nil {
		return "", err
	}

	dir := filepath.Dir(abs)
	info, err := os.Stat(dir)
	if err != nil {
		return "", fmt.Errorf("output directory %q: %w", dir, err)
	}
	if !info.IsDir() {
		return "", fmt.Errorf("output directory %q is not a directory", dir)
	}

	body, err := marshalInstallConfig(cfg)
	if err != nil {
		return "", err
	}

	file, err := os.CreateTemp(dir, ".install-config-*")
	if err != nil {
		return "", err
	}
	tempName := file.Name()
	discard := func() {
		file.Close()
		os.Remove(tempName)
	}

	if err := file.Chmod(0600); err != nil {
		discard()
		return "", err
	}
	if _, err := file.WriteString(installConfigHeader); err != nil {
		discard()
		return "", err
	}
	if _, err := file.Write(body); err != nil {
		discard()
		return "", err
	}
	if err := file.Sync(); err != nil {
		discard()
		return "", err
	}
	if err := file.Close(); err != nil {
		os.Remove(tempName)
		return "", err
	}
	if err := os.Rename(tempName, abs); err != nil {
		os.Remove(tempName)
		return "", err
	}

	return abs, nil
}
